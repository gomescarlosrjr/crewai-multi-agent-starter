"""
Client for calling the Gemini language model (LLM).

This module wraps the configuration and use of the `google-generativeai` SDK to
access the Gemini API. Specifically, we use the "gemini-2.0-flash" model or
another one specified via an environment variable. The API key must be set in
the `GEMINI_API_KEY` variable in `.env`.

For more details about the SDK, see Google's official documentation. The
`generate_content` method below sends a text prompt and returns the model's
response as a string.
"""
import os
from typing import List, Optional

try:
    from dotenv import load_dotenv
    # Load .env variables if the library is available
    load_dotenv()
except ImportError:
    # If python-dotenv is not installed, we ignore it. Environment
    # variables must be configured by other means.
    load_dotenv = lambda *args, **kwargs: None  # type: ignore

# Importing the Google Gen AI SDK may fail if the library is not installed
# or if there is no connectivity. Make sure to include
# `google-generativeai` in requirements.txt.
try:
    import google.generativeai as genai
except ImportError:
    genai = None

load_dotenv()


def _configure() -> None:
    """Configure the genai library with the .env key if not done yet."""
    # Fake mode for bootcamp/offline testing
    if os.getenv("FAKE_LLM") == "1":
        return
    if genai is None:
        raise ImportError(
            "The google-generativeai package is not installed. Add it to requirements.txt."
        )
    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key:
        raise EnvironmentError(
            "GEMINI_API_KEY is not set. Create a .env file with your key."
        )
    # Configure the API key only once. The SDK keeps global state.
    genai.configure(api_key=api_key)


def generate_content(prompt: str, model_name: Optional[str] = None) -> str:
    """Generate text content using the Gemini model.

    Args:
        prompt (str): text input (may include context retrieved via RAG).
        model_name (str, optional): model name. If None, uses
            'gemini-2.0-flash'.

    Returns:
        str: text generated by the model.

    Raises:
        Exception: if an error occurs during the API call.
    """
    _configure()
    if os.getenv("FAKE_LLM") == "1":
        return f"[FAKE_LLM] Response generated from the prompt:\n{prompt[:400]}..."
    model_name = model_name or "gemini-2.0-flash"
    try:
        model = genai.GenerativeModel(model_name)
        response = model.generate_content(prompt)
        return response.text
    except Exception as exc:
        raise RuntimeError(f"Error calling the Gemini model: {exc}") from exc


def chat_with_history(messages: List[dict], model_name: Optional[str] = None) -> str:
    """Send a list of messages to the Gemini model in chat format.

    Args:
        messages (List[dict]): messages in the format
            [{'role': 'user', 'content': '...'}, {'role': 'assistant', 'content': '...'}, ...]
        model_name (str, optional): model name (default gemini-2.0-flash).
    Returns:
        str: the response generated by the model.

    Note: this function is provided as a multi-turn chat example. Use it when
    you need to provide conversation history to the model. The Gemini SDK
    accepts this format.
    """
    _configure()
    if os.getenv("FAKE_LLM") == "1":
        return "[FAKE_LLM] Simulated chat with history (messages truncated)."
    model_name = model_name or "gemini-2.0-flash"
    try:
        model = genai.GenerativeModel(model_name)
        response = model.generate_content(messages)
        return response.text
    except Exception as exc:
        raise RuntimeError(f"Error in chat with the Gemini model: {exc}") from exc
